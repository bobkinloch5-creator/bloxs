const CANONICAL = (slug: string) => `https://bloxsmith.pro/guides/${slug}`;

export const Route = createFileRoute("/guides/$slug")({
  head: ({ params }) => {
    const g = GUIDES[params.slug];
    if (!g) {
      return { meta: [{ title: "Guide not found — BloxSmith" }] };
    }
    const url = CANONICAL(g.meta.slug);
    return {
      meta: [
        { title: `${g.meta.title} | BloxSmith` },
        { name: "description", content: g.meta.description },
        { property: "og:title", content: g.meta.title },
        { property: "og:description", content: g.meta.description },
        { property: "og:type", content: "article" },
        { property: "og:url", content: url },
      ],
      links: [{ rel: "canonical", href: url }],
      scripts: [
        { type: "application/ld+json", children: JSON.stringify({
          "@context": "https://schema.org",
          "@type": "Article",
          headline: g.meta.title,
          description: g.meta.description,
          datePublished: g.meta.datePublished,
          author: { "@type": "Organization", name: "BloxSmith" },
          publisher: { "@type": "Organization", name: "BloxSmith", logo: { "@type": "ImageObject", url: "https://bloxsmith.pro/favicon.ico" } },
          mainEntityOfPage: url,
        }) },
        { type: "application/ld+json", children: JSON.stringify(breadcrumbJsonLd([
          { name: "Home", url: "https://bloxsmith.pro/" },
          { name: "Guides", url: "https://bloxsmith.pro/guides" },
          { name: g.meta.title, url },
        ])) },
      ],
    };
  },
  component: GuidePage,
  notFoundComponent: () => <p className="p-10 text-center text-white">Guide not found.</p>,
});

