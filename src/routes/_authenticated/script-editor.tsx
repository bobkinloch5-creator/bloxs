import { createFileRoute } from "@tanstack/react-router";
import { useServerFn } from "@tanstack/react-start";
import { getMyProfile } from "@/lib/profile.functions";
import { useQuery } from "@tanstack/react-query";
import { PageShell } from "@/components/PageShell";
import {
  FileCode, Code2, Download, Copy, Check, RefreshCw, Sparkles,
  AlertTriangle, Zap, ShieldCheck, Upload, Layers, Server, Monitor,
  Package, Plus, Trash2, Search, Play, CheckCircle2, X,
} from "lucide-react";
import { useCallback, useEffect, useRef, useState } from "react";
import { toast } from "sonner";

export const Route = createFileRoute("/_authenticated/script-editor")({
  head: () => ({
    meta: [
      { title: "Script Editor — BloxSmith" },
      { name: "description", content: "AI-powered Luau script editor. Write, generate, organize, and export production-ready Roblox scripts." },
      { name: "robots", content: "noindex, nofollow" },
    ],
  }),
  component: ScriptEditor,
});

type ScriptType = "Script" | "LocalScript" | "ModuleScript";
type Service =
  | "ServerScriptService"
  | "StarterPlayer.StarterPlayerScripts"
  | "StarterPlayer.StarterCharacterScripts"
  | "StarterGui"
  | "ReplicatedStorage"
  | "ReplicatedFirst"
  | "ServerStorage"
  | "StarterPack"
  | "Workspace";

interface ScriptFile {
  id: string;
  name: string;
  type: ScriptType;
  service: Service;
  content: string;
  error?: string | null;
}

const SERVICE_OPTIONS: { value: Service; label: string }[] = [
  { value: "ServerScriptService", label: "ServerScriptService" },
  { value: "StarterPlayer.StarterPlayerScripts", label: "StarterPlayerScripts" },
  { value: "StarterPlayer.StarterCharacterScripts", label: "StarterCharacterScripts" },
  { value: "StarterGui", label: "StarterGui" },
  { value: "ReplicatedStorage", label: "ReplicatedStorage" },
  { value: "ReplicatedFirst", label: "ReplicatedFirst" },
  { value: "ServerStorage", label: "ServerStorage" },
  { value: "StarterPack", label: "StarterPack" },
  { value: "Workspace", label: "Workspace" },
];

const SCRIPT_TEMPLATES: Record<ScriptType, string> = {
  Script: `-- ServerScript: Place in ServerScriptService
-- Generated by BloxSmith

local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")

-- Create RemoteEvents folder
local Remotes = Instance.new("Folder")
Remotes.Name = "Remotes"
Remotes.Parent = ReplicatedStorage

-- Player added handler
Players.PlayerAdded:Connect(function(player)
	-- Initialize player data
	local leaderstats = Instance.new("Folder")
	leaderstats.Name = "leaderstats"
	leaderstats.Parent = player

	local coins = Instance.new("IntValue")
	coins.Name = "Coins"
	coins.Value = 0
	coins.Parent = leaderstats
end)
`,
  LocalScript: `-- LocalScript: Place in StarterPlayerScripts
-- Generated by BloxSmith

local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local UserInputService = game:GetService("UserInputService")

local player = Players.LocalPlayer
local character = player.Character or player.CharacterAdded:Wait()
local humanoid = character:WaitForChild("Humanoid")

-- Listen for input
UserInputService.InputBegan:Connect(function(input, processed)
	if processed then return end
	if input.KeyCode == Enum.KeyCode.E then
		-- Interact logic here
	end
end)
`,
  ModuleScript: `-- ModuleScript: Place in ReplicatedStorage
-- Generated by BloxSmith

local Module = {}

-- Configuration
Module.Config = {
	MaxCoins = 99999,
	StartingCoins = 0,
	CoinMultiplier = 1,
}

-- Utility function
function Module.FormatNumber(n: number): string
	if n >= 1_000_000 then
		return string.format("%.1fM", n / 1_000_000)
	elseif n >= 1_000 then
		return string.format("%.1fK", n / 1_000)
	end
	return tostring(n)
end

return Module
`,
};

const QUICK_SCRIPTS = [
  { label: "Leaderstats", prompt: "Generate leaderstats with Coins and XP that save with DataStore." },
  { label: "Proximity Prompt", prompt: "Generate a ProximityPrompt interaction that gives coins when triggered." },
  { label: "Shop Handler", prompt: "Generate a server-side shop handler using RemoteEvents with security checks." },
  { label: "NPC Dialogue", prompt: "Generate an NPC dialogue system with choice bubbles and branching responses." },
  { label: "Checkpoint System", prompt: "Generate a checkpoint system that saves player progress across sessions." },
  { label: "Tool Handler", prompt: "Generate a reusable tool handler with equip/unequip animations and cooldowns." },
  { label: "Admin Commands", prompt: "Generate a basic admin command system restricted to owner UserIds." },
  { label: "DataStore Save", prompt: "Generate a robust DataStore save/load system with retry logic and PCalls." },
];

function ScriptEditor() {
  const profFn = useServerFn(getMyProfile);
  const { data: profile } = useQuery({ queryKey: ["profile"], queryFn: () => profFn() });
  const isAdmin = !!profile?.is_admin;

  const [scripts, setScripts] = useState<ScriptFile[]>([
    {
      id: "1",
      name: "MainGameScript",
      type: "Script",
      service: "ServerScriptService",
      content: SCRIPT_TEMPLATES.Script,
    },
  ]);
  const [activeId, setActiveId] = useState("1");
  const [search, setSearch] = useState("");
  const [copied, setCopied] = useState(false);
  const [importing, setImporting] = useState(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const active = scripts.find((s) => s.id === activeId) ?? scripts[0];

  function addScript() {
    const id = crypto.randomUUID();
    const newScript: ScriptFile = {
      id,
      name: `Script${scripts.length + 1}`,
      type: "Script",
      service: "ServerScriptService",
      content: SCRIPT_TEMPLATES.Script,
    };
    setScripts((prev) => [...prev, newScript]);
    setActiveId(id);
  }

  function deleteScript(id: string) {
    if (scripts.length <= 1) { toast.error("Keep at least one script."); return; }
    const next = scripts.filter((s) => s.id !== id);
    setScripts(next);
    if (activeId === id) setActiveId(next[0].id);
  }

  function updateActive(patch: Partial<ScriptFile>) {
    setScripts((prev) => prev.map((s) => (s.id === activeId ? { ...s, ...patch } : s)));
  }

  function applyTemplate(type: ScriptType) {
    updateActive({ type, content: SCRIPT_TEMPLATES[type] });
  }

  async function copyScript() {
    if (!active) return;
    try {
      await navigator.clipboard.writeText(active.content);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error("Copy failed — try the Download button instead.");
    }
  }

  function downloadScript() {
    if (!active) return;
    const ext = ".lua";
    const blob = new Blob([active.content], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${active.name}${ext}`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  }

  function downloadAll() {
    scripts.forEach((s) => {
      const blob = new Blob([s.content], { type: "text/plain;charset=utf-8" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${s.name}.lua`;
      document.body.appendChild(a);
      a.click();
      a.remove();
      URL.revokeObjectURL(url);
    });
    toast.success(`Downloaded ${scripts.length} scripts.`);
  }

  function handleImport(e: React.ChangeEvent<HTMLInputElement>) {
    const files = Array.from(e.target.files ?? []);
    if (!files.length) return;
    setImporting(true);
    const readers = files.map(
      (f) =>
        new Promise<ScriptFile>((resolve) => {
          const reader = new FileReader();
          reader.onload = () => {
            const id = crypto.randomUUID();
            const name = f.name.replace(/\.(lua|luau)$/, "");
            resolve({ id, name, type: "Script", service: "ServerScriptService", content: String(reader.result) });
          };
          reader.readAsText(f);
        })
    );
    Promise.all(readers).then((imported) => {
      setScripts((prev) => [...prev, ...imported]);
      setActiveId(imported[0].id);
      toast.success(`Imported ${imported.length} script${imported.length !== 1 ? "s" : ""}.`);
      setImporting(false);
    });
    e.target.value = "";
  }

  const filtered = search
    ? scripts.filter((s) => s.name.toLowerCase().includes(search.toLowerCase()))
    : scripts;

  const typeIcon = (type: ScriptType) =>
    type === "Script" ? <Server className="h-3.5 w-3.5 text-emerald-400" /> :
    type === "LocalScript" ? <Monitor className="h-3.5 w-3.5 text-blue-400" /> :
    <Package className="h-3.5 w-3.5 text-violet-400" />;

  return (
    <PageShell
      title="Script Editor"
      description="Write, import, organize, and export production-ready Luau scripts. All scripts auto-target the correct Roblox service."
      accent="chat"
      activeKey="scripts"
      isAdmin={isAdmin}
    >
      {/* Top toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-white/10 bg-white/[0.03] px-4 py-3">
        <div className="flex flex-wrap items-center gap-2">
          <div className="flex items-center gap-1.5 rounded-xl border border-white/10 bg-black/30 px-3 py-1.5 text-xs font-semibold text-slate-300">
            <Layers className="h-3.5 w-3.5 text-indigo-400" />
            {scripts.length} script{scripts.length !== 1 ? "s" : ""}
          </div>
          <button onClick={addScript} className="inline-flex items-center gap-1.5 rounded-xl border border-indigo-400/30 bg-indigo-500/15 px-3 py-1.5 text-xs font-bold text-indigo-100 hover:bg-indigo-500/25">
            <Plus className="h-3.5 w-3.5" /> New Script
          </button>
          <button
            onClick={() => fileInputRef.current?.click()}
            disabled={importing}
            className="inline-flex items-center gap-1.5 rounded-xl border border-white/10 bg-white/[0.05] px-3 py-1.5 text-xs font-bold text-slate-200 hover:bg-white/[0.1] disabled:opacity-50"
          >
            <Upload className="h-3.5 w-3.5" /> Import .lua
          </button>
          <input ref={fileInputRef} type="file" accept=".lua,.luau" multiple hidden onChange={handleImport} />
        </div>
        <div className="flex items-center gap-2">
          <button onClick={copyScript} className="inline-flex items-center gap-1.5 rounded-xl border border-white/10 bg-white/[0.04] px-3 py-1.5 text-xs font-bold text-slate-200 hover:bg-white/[0.09]">
            {copied ? <Check className="h-3.5 w-3.5 text-emerald-300" /> : <Copy className="h-3.5 w-3.5" />}
            {copied ? "Copied!" : "Copy Active"}
          </button>
          <button onClick={downloadScript} className="inline-flex items-center gap-1.5 rounded-xl border border-emerald-400/30 bg-emerald-500/15 px-3 py-1.5 text-xs font-bold text-emerald-100 hover:bg-emerald-500/25">
            <Download className="h-3.5 w-3.5" /> Download
          </button>
          <button onClick={downloadAll} className="inline-flex items-center gap-1.5 rounded-xl border border-amber-400/30 bg-amber-500/15 px-3 py-1.5 text-xs font-bold text-amber-100 hover:bg-amber-500/25">
            <Download className="h-3.5 w-3.5" /> Export All
          </button>
        </div>
      </div>

      {/* Quick scripts */}
      <div className="rounded-2xl border border-white/10 bg-white/[0.02] p-4">
        <div className="mb-3 text-xs font-bold uppercase tracking-wider text-slate-400">Quick Scripts</div>
        <div className="flex flex-wrap gap-2">
          {QUICK_SCRIPTS.map((qs) => (
            <button
              key={qs.label}
              onClick={() => {
                const id = crypto.randomUUID();
                setScripts((prev) => [
                  ...prev,
                  { id, name: qs.label.replace(/\s+/g, ""), type: "Script", service: "ServerScriptService", content: `-- ${qs.prompt}\n-- Generated by BloxSmith\n-- Paste your AI-generated code here after describing this in the Build chat.\n\nprint("${qs.label} ready")\n` },
                ]);
                setActiveId(id);
                toast.info(`Created "${qs.label}" — use Build chat to fill it in.`);
              }}
              className="inline-flex items-center gap-1.5 rounded-xl border border-white/10 bg-white/[0.04] px-3 py-1.5 text-[11px] font-semibold text-slate-300 hover:border-indigo-400/40 hover:bg-indigo-500/10 hover:text-indigo-200"
            >
              <Sparkles className="h-3 w-3 text-indigo-400" /> {qs.label}
            </button>
          ))}
        </div>
      </div>

      {/* Main editor layout */}
      <div className="grid gap-4 lg:grid-cols-[280px_1fr]">
        {/* File tree */}
        <div className="rounded-2xl border border-white/10 bg-white/[0.02] p-3">
          <div className="mb-2 flex items-center gap-2 rounded-xl border border-white/10 bg-black/30 px-3 py-2">
            <Search className="h-3.5 w-3.5 text-slate-500" />
            <input
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              placeholder="Search scripts…"
              className="flex-1 bg-transparent text-xs text-slate-200 outline-none placeholder:text-slate-500"
            />
            {search && <button onClick={() => setSearch("")}><X className="h-3 w-3 text-slate-500" /></button>}
          </div>
          <ul className="space-y-0.5">
            {filtered.map((s) => (
              <li key={s.id}>
                <button
                  onClick={() => setActiveId(s.id)}
                  className={`group flex w-full items-center gap-2 rounded-xl px-3 py-2 text-left text-xs font-medium transition ${s.id === activeId ? "bg-indigo-500/20 text-white border border-indigo-400/30" : "text-slate-400 hover:bg-white/[0.04] hover:text-slate-200"}`}
                >
                  {typeIcon(s.type)}
                  <span className="flex-1 truncate">{s.name}</span>
                  <button
                    onClick={(e) => { e.stopPropagation(); deleteScript(s.id); }}
                    className="hidden text-slate-600 hover:text-red-400 group-hover:block"
                  >
                    <Trash2 className="h-3 w-3" />
                  </button>
                </button>
              </li>
            ))}
          </ul>
        </div>

        {/* Editor area */}
        {active && (
          <div className="flex flex-col gap-3">
            {/* Script metadata */}
            <div className="grid grid-cols-2 gap-3 rounded-2xl border border-white/10 bg-white/[0.02] p-4 sm:grid-cols-4">
              <div>
                <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400">Name</label>
                <input
                  value={active.name}
                  onChange={(e) => updateActive({ name: e.target.value })}
                  className="mt-1 w-full rounded-lg border border-white/10 bg-black/30 px-2.5 py-1.5 text-xs text-slate-100 outline-none focus:border-indigo-400/50"
                />
              </div>
              <div>
                <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400">Type</label>
                <select
                  value={active.type}
                  onChange={(e) => applyTemplate(e.target.value as ScriptType)}
                  className="mt-1 w-full rounded-lg border border-white/10 bg-black/30 px-2.5 py-1.5 text-xs text-slate-100 outline-none"
                >
                  <option value="Script">ServerScript</option>
                  <option value="LocalScript">LocalScript</option>
                  <option value="ModuleScript">ModuleScript</option>
                </select>
              </div>
              <div className="sm:col-span-2">
                <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400">Service / Location</label>
                <select
                  value={active.service}
                  onChange={(e) => updateActive({ service: e.target.value as Service })}
                  className="mt-1 w-full rounded-lg border border-white/10 bg-black/30 px-2.5 py-1.5 text-xs text-slate-100 outline-none"
                >
                  {SERVICE_OPTIONS.map((opt) => (
                    <option key={opt.value} value={opt.value}>{opt.label}</option>
                  ))}
                </select>
              </div>
            </div>

            {/* Code area */}
            <div className="overflow-hidden rounded-2xl border border-white/10">
              <div className="flex items-center justify-between border-b border-white/10 bg-black/50 px-4 py-2">
                <div className="flex items-center gap-2 text-[11px] font-semibold text-slate-300">
                  {typeIcon(active.type)}
                  <span>{active.name}</span>
                  <span className="text-slate-500">→ {active.service}</span>
                </div>
                <div className="flex items-center gap-1.5">
                  <span className="text-[10px] text-slate-500">{active.content.split("\n").length} lines</span>
                </div>
              </div>
              <textarea
                value={active.content}
                onChange={(e) => updateActive({ content: e.target.value })}
                spellCheck={false}
                className="min-h-[480px] w-full resize-y bg-[#0a0a1a] p-4 font-mono text-[12.5px] leading-relaxed text-slate-100 outline-none"
                style={{ fontFamily: "'Space Mono', 'Fira Code', ui-monospace, monospace", tabSize: 2 }}
              />
            </div>

            {/* Status bar */}
            <div className="flex flex-wrap items-center gap-4 rounded-xl border border-white/10 bg-black/20 px-4 py-2 text-[11px] text-slate-400">
              <span className="flex items-center gap-1.5"><CheckCircle2 className="h-3 w-3 text-emerald-400" /> Lua 5.1 / Luau</span>
              <span className="flex items-center gap-1.5"><ShieldCheck className="h-3 w-3 text-blue-400" /> {active.type}</span>
              <span className="flex items-center gap-1.5"><Layers className="h-3 w-3 text-indigo-400" /> {active.service}</span>
              <span className="ml-auto">{active.content.length} chars · {active.content.split("\n").length} lines</span>
            </div>
          </div>
        )}
      </div>

      {/* Export info */}
      <div className="rounded-2xl border border-indigo-400/20 bg-indigo-500/5 p-4">
        <div className="flex items-start gap-3">
          <span className="mt-0.5 grid h-8 w-8 shrink-0 place-items-center rounded-xl bg-indigo-500/20 text-indigo-300">
            <FileCode className="h-4 w-4" />
          </span>
          <div>
            <div className="text-sm font-bold text-white">How to use in Roblox Studio</div>
            <ol className="mt-2 space-y-1 text-[12px] text-slate-300">
              <li>1. Download the script (.lua file) using the button above.</li>
              <li>2. Open Roblox Studio and navigate to the target service shown in the "Service / Location" field.</li>
              <li>3. Right-click the service → Insert Object → choose the matching Script type.</li>
              <li>4. Paste the code, or drag the .lua file into Studio's Explorer panel.</li>
              <li>5. If you have the BloxSmith plugin installed, use <strong>Build</strong> mode to send scripts directly.</li>
            </ol>
          </div>
        </div>
      </div>
    </PageShell>
  );
}
