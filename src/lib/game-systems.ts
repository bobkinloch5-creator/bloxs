const TRADING = `${header("Trading - two-sided confirm, anti-scam locks, server authoritative", "Trading:Request(from, to)")}
local Players = game:GetService("Players")
local Profiles = require(script.Parent.ProfileStore)

local Trading = {}
local sessions = {}
local CONFIRM_LOCK_SECONDS = 2

local function sessionFor(player)
	return sessions[player]
end

local function ownsAll(player, items)
	local inventory = Profiles:Get(player).inventory
	for _, item in ipairs(items) do
		local found = false
		for _, slot in ipairs(inventory) do
			if slot.id == item.id and slot.count >= (item.count or 1) then
				found = true
				break
			end
		end
		if not found then
			return false
		end
	end
	return true
end

local function move(fromPlayer, toPlayer, items)
	local fromInventory = Profiles:Get(fromPlayer).inventory
	local toInventory = Profiles:Get(toPlayer).inventory
	for _, item in ipairs(items) do
		local amount = item.count or 1
		for index, slot in ipairs(fromInventory) do
			if slot.id == item.id then
				slot.count -= amount
				if slot.count <= 0 then
					table.remove(fromInventory, index)
				end
				break
			end
		end
		local merged = false
		for _, slot in ipairs(toInventory) do
			if slot.id == item.id then
				slot.count += amount
				merged = true
				break
			end
		end
		if not merged then
			table.insert(toInventory, { id = item.id, count = amount })
		end
	end
end

function Trading:Request(from, to)
	if sessionFor(from) or sessionFor(to) then
		return false, "busy"
	end
	local session = {
		a = from,
		b = to,
		offers = { [from] = {}, [to] = {} },
		confirmed = { [from] = false, [to] = false },
		changedAt = os.clock(),
	}
	sessions[from] = session
	sessions[to] = session
	return true, session
end

function Trading:SetOffer(player, items)
	local session = sessionFor(player)
	if not session then
		return false, "no_session"
	end
	if not ownsAll(player, items) then
		return false, "missing_items"
	end
	session.offers[player] = items
	-- Any offer change resets confirmations: classic anti-scam rule.
	session.confirmed[session.a] = false
	session.confirmed[session.b] = false
	session.changedAt = os.clock()
	return true
end

function Trading:Confirm(player)
	local session = sessionFor(player)
	if not session then
		return false, "no_session"
	end
	if os.clock() - session.changedAt < CONFIRM_LOCK_SECONDS then
		return false, "locked"
	end
	session.confirmed[player] = true
	if session.confirmed[session.a] and session.confirmed[session.b] then
		if not ownsAll(session.a, session.offers[session.a]) or not ownsAll(session.b, session.offers[session.b]) then
			self:Cancel(player)
			return false, "validation_failed"
		end
		move(session.a, session.b, session.offers[session.a])
		move(session.b, session.a, session.offers[session.b])
		sessions[session.a] = nil
		sessions[session.b] = nil
		return true, "completed"
	end
	return true, "waiting"
end

function Trading:Cancel(player)
	local session = sessionFor(player)
	if not session then
		return false
	end
	sessions[session.a] = nil
	sessions[session.b] = nil
	return true
end

Players.PlayerRemoving:Connect(function(player)
	Trading:Cancel(player)
end)

return Trading`;

