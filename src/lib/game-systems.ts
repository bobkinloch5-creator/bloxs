const MATCHMAKING = `${header("Matchmaking - queue, round loop, teleports and private servers", "Matchmaking:Queue(player)")}
local Players = game:GetService("Players")
local TeleportService = game:GetService("TeleportService")

local Matchmaking = {}
Matchmaking.MinPlayers = 2
Matchmaking.MaxPlayers = 12
Matchmaking.IntermissionSeconds = 15
Matchmaking.RoundSeconds = 180
Matchmaking.PlaceId = game.PlaceId

local queue = {}
local listeners = {}

function Matchmaking:OnStateChanged(callback)
	table.insert(listeners, callback)
end

local function emit(state, payload)
	for _, callback in ipairs(listeners) do
		task.spawn(callback, state, payload)
	end
end

function Matchmaking:Queue(player)
	if table.find(queue, player) then
		return false
	end
	table.insert(queue, player)
	emit("queued", { count = #queue })
	return true
end

function Matchmaking:Leave(player)
	local index = table.find(queue, player)
	if index then
		table.remove(queue, index)
		emit("queued", { count = #queue })
	end
end

function Matchmaking:CreatePrivateServer(host, friends)
	local ok, code = pcall(function()
		return TeleportService:ReserveServer(self.PlaceId)
	end)
	if not ok then
		return false, code
	end
	local party = { host }
	for _, friend in ipairs(friends or {}) do
		table.insert(party, friend)
	end
	pcall(function()
		TeleportService:TeleportToPrivateServer(self.PlaceId, code, party)
	end)
	return true, code
end

function Matchmaking:Start()
	task.spawn(function()
		while true do
			emit("intermission", { seconds = self.IntermissionSeconds })
			task.wait(self.IntermissionSeconds)

			local roster = {}
			for _, player in ipairs(#queue > 0 and queue or Players:GetPlayers()) do
				if player and player.Parent and #roster < self.MaxPlayers then
					table.insert(roster, player)
				end
			end

			if #roster >= self.MinPlayers then
				emit("round_start", { roster = roster })
				task.wait(self.RoundSeconds)
				emit("round_end", { roster = roster })
				table.clear(queue)
			else
				emit("waiting", { needed = self.MinPlayers - #roster })
				task.wait(3)
			end
		end
	end)
end

Players.PlayerRemoving:Connect(function(player)
	Matchmaking:Leave(player)
end)

return Matchmaking`;

