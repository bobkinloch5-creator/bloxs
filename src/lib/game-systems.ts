export const SYSTEM_KEYS = GAME_SYSTEMS.map((system) => system.key);

export function getSystem(key: string): GameSystem | undefined {
  return GAME_SYSTEMS.find((system) => system.key === key);
}

/** Detect requested systems from a natural-language prompt. */
export function detectSystems(prompt: string): GameSystem[] {
  return GAME_SYSTEMS.filter((system) => system.keywords.test(prompt));
}

/** Expand a system selection to include every dependency, in install order. */
export function resolveSystemOrder(keys: string[]): GameSystem[] {
  const out: GameSystem[] = [];
  const seen = new Set<string>();
  const visit = (key: string, stack: Set<string>) => {
    if (seen.has(key) || stack.has(key)) return;
    const system = getSystem(key);
    if (!system) return;
    stack.add(key);
    for (const dep of system.requires ?? []) visit(dep, stack);
    stack.delete(key);
    seen.add(key);
    out.push(system);
  };
  for (const key of keys) visit(key, new Set());
  return out;
}

/** Parent path for a system module. */
export function systemParentPath(system: GameSystem): string {
  return system.slot === "serverModule" ? SERVICE_ROUTES.serverModule : SERVICE_ROUTES.sharedModule;
}

/** Boot Script that requires every installed system exactly once. */
export function buildSystemsBootstrap(systems: GameSystem[]): string {
  const lines = systems
    .filter((system) => system.slot === "serverModule")
    .map((system) => `\tsafeRequire("${system.name}")`);
  return [
    "--[[",
    "\tBloxSmith bootstrap - starts every generated server system once.",
    "\tAdding your own module? Just drop it in BloxSmith_Systems and add a line.",
    "]]",
    'local systems = game:GetService("ServerScriptService"):WaitForChild("BloxSmith_Systems")',
    "",
    "local loaded = {}",
    "",
    "local function safeRequire(name)",
    "\tlocal module = systems:FindFirstChild(name)",
    "\tif not module then",
    '\t\twarn(("[BloxSmith] Missing system module: %s"):format(name))',
    "\t\treturn nil",
    "\tend",
    "\tlocal ok, result = pcall(require, module)",
    "\tif not ok then",
    '\t\twarn(("[BloxSmith] System %s failed to start: %s"):format(name, tostring(result)))',
    "\t\treturn nil",
    "\tend",
    "\tloaded[name] = result",
    "\treturn result",
    "end",
    "",
    "do",
    ...lines,
    "end",
    "",
    'print(("[BloxSmith] %d server system(s) online"):format(#systems:GetChildren()))',
    "return loaded",
  ].join("\n");
}
